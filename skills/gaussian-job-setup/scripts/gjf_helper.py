#!/usr/bin/env python3
"""Standalone Gaussian 16 GJF input generator, syntax/safety validator & route advisor.

Stdlib-only CLI bundled with the gaussian-job-setup skill so it works without
requiring any external Python dependencies or a hosted MCP server.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any, Dict, List, Tuple

ELEMENT_Z: Dict[str, int] = {
    "H": 1, "HE": 2, "LI": 3, "BE": 4, "B": 5, "C": 6, "N": 7, "O": 8, "F": 9, "NE": 10,
    "NA": 11, "MG": 12, "AL": 13, "SI": 14, "P": 15, "S": 16, "CL": 17, "AR": 18,
    "K": 19, "CA": 20, "SC": 21, "TI": 22, "V": 23, "CR": 24, "MN": 25, "FE": 26,
    "CO": 27, "NI": 28, "CU": 29, "ZN": 30, "GA": 31, "GE": 32, "AS": 33, "SE": 34,
    "BR": 35, "KR": 36, "RB": 37, "SR": 38, "Y": 39, "ZR": 40, "NB": 41, "MO": 42,
    "TC": 43, "RU": 44, "RH": 45, "PD": 46, "AG": 47, "CD": 48, "IN": 49, "SN": 50,
    "SB": 51, "TE": 52, "I": 53, "XE": 54, "CS": 55, "BA": 56, "PT": 78, "AU": 79,
    "HG": 80, "PB": 82, "BI": 83,
}

JOB_PRESETS: Dict[str, str] = {
    "sp": "",
    "opt": "opt",
    "freq": "freq",
    "opt_freq": "opt freq",
    "ts": "opt=(calcfc,ts,noeigen) freq",
    "irc_forward": "irc=(calcfc,forward,maxpoints=30)",
    "irc_reverse": "irc=(calcfc,reverse,maxpoints=30)",
    "td": "td=(nstates=6)",
    "nmr": "nmr=giao",
}

MEM_RE = re.compile(r"^\d+(?:MB|GB|MW|GW)$", re.IGNORECASE)
CHK_SAFE_RE = re.compile(r"^[A-Za-z0-9._-]+$")
RESERVED_DOS = {"CON", "PRN", "AUX", "NUL"} | {f"{p}{i}" for p in ("COM", "LPT") for i in range(1, 10)}


def _validate_single_line(label: str, value: str) -> None:
    if any(ch in value for ch in ("\r", "\n", "\x00")):
        raise ValueError(f"{label} contains forbidden newline or control character")


def parse_xyz(text: str) -> Tuple[str, List[Tuple[str, float, float, float]]]:
    lines = text.splitlines()
    if len(lines) < 3:
        raise ValueError("XYZ input must contain at least 3 lines (atom count, comment, coordinates)")
    try:
        n_declared = int(lines[0].strip())
    except ValueError as exc:
        raise ValueError(f"First XYZ line must be integer atom count, got: {lines[0]!r}") from exc
    title = lines[1].strip() or "Generated by gaussian-job-setup"
    atoms: List[Tuple[str, float, float, float]] = []
    for raw in lines[2:]:
        s = raw.strip()
        if not s:
            continue
        parts = s.split()
        if len(parts) < 4:
            raise ValueError(f"Malformed XYZ coordinate line: {raw!r}")
        sym = parts[0].strip()
        try:
            x, y, z = float(parts[1]), float(parts[2]), float(parts[3])
        except ValueError as exc:
            raise ValueError(f"Non-numeric coordinate in XYZ line: {raw!r}") from exc
        atoms.append((sym, x, y, z))
    if len(atoms) != n_declared:
        raise ValueError(f"XYZ atom count mismatch: header={n_declared}, parsed={len(atoms)}")
    return title, atoms


def electron_parity_check(atoms: List[Tuple[str, float, float, float]], charge: int, multiplicity: int) -> List[str]:
    warnings: List[str] = []
    total_z = 0
    for sym, _, _, _ in atoms:
        key = sym.upper()
        if key not in ELEMENT_Z:
            return warnings
        total_z += ELEMENT_Z[key]
    n_electrons = total_z - charge
    if n_electrons < 0:
        warnings.append(f"Negative electron count ({n_electrons}) for charge={charge}")
    elif (n_electrons % 2) != ((multiplicity - 1) % 2):
        warnings.append(
            f"Spin multiplicity parity mismatch: {n_electrons} electrons cannot have multiplicity={multiplicity}"
        )
    return warnings


def build_gjf(
    atoms: List[Tuple[str, float, float, float]],
    *,
    method: str = "B3LYP",
    basis: str = "6-31G(d,p)",
    job_type: str = "opt_freq",
    charge: int = 0,
    multiplicity: int = 1,
    mem: str = "8GB",
    nproc: int = 4,
    chk: str = "",
    solvent: str = "",
    dispersion: str = "",
    title: str = "Gaussian calculation",
    extra_keywords: str = "",
) -> str:
    for lbl, val in (
        ("method", method), ("basis", basis), ("mem", mem), ("chk", chk),
        ("solvent", solvent), ("dispersion", dispersion), ("extra_keywords", extra_keywords),
    ):
        _validate_single_line(lbl, val)
    if nproc <= 0 or nproc > 128:
        raise ValueError(f"nproc must be within 1..128, got {nproc}")
    if not MEM_RE.match(mem.strip()):
        raise ValueError(f"mem must look like '8GB' or '1600MB', got {mem!r}")
    if multiplicity < 1:
        raise ValueError(f"multiplicity must be >= 1, got {multiplicity}")
    if job_type not in JOB_PRESETS:
        raise ValueError(f"Unsupported job_type={job_type!r}. Choices: {', '.join(JOB_PRESETS)}")

    link0 = [f"%mem={mem.strip()}", f"%nprocshared={nproc}"]
    if chk.strip():
        chk_clean = chk.strip()
        if "/" in chk_clean or "\\" in chk_clean or ".." in chk_clean or not CHK_SAFE_RE.match(chk_clean):
            raise ValueError(f"chk must be a plain filename without path separators: {chk!r}")
        if Path(chk_clean).stem.upper() in RESERVED_DOS:
            raise ValueError(f"Reserved DOS device name in chk: {chk_clean!r}")
        link0.append(f"%chk={chk_clean}")

    route_parts = [f"#p {method.strip()}/{basis.strip()}"]
    preset_kw = JOB_PRESETS[job_type]
    if preset_kw:
        route_parts.append(preset_kw)
    if dispersion.strip():
        route_parts.append(f"EmpiricalDispersion={dispersion.strip()}")
    if solvent.strip():
        route_parts.append(f"scrf=(iefpcm,solvent={solvent.strip()})")
    if extra_keywords.strip():
        route_parts.append(extra_keywords.strip())

    clean_title = " ".join(title.splitlines()).strip() or "Gaussian calculation"
    coord_lines = [f" {sym:<3s}  {x:14.8f}  {y:14.8f}  {z:14.8f}" for sym, x, y, z in atoms]
    sections = [
        *link0,
        " ".join(route_parts),
        "",
        clean_title,
        "",
        f"{charge} {multiplicity}",
        *coord_lines,
        "",
        "",
    ]
    return "\n".join(sections)


def validate_gjf(text: str) -> Dict[str, Any]:
    errors: List[str] = []
    warnings: List[str] = []
    if "\r\n" in text:
        warnings.append("File uses CRLF line endings; LF is recommended on Linux HPC clusters.")
    if not text.endswith("\n\n") and not text.endswith("\r\n\r\n"):
        errors.append("Gaussian .gjf files must end with at least one blank line after geometry.")

    lines = text.splitlines()
    link0_lines: List[str] = []
    route_lines: List[str] = []
    i = 0
    while i < len(lines) and lines[i].strip().startswith("%"):
        l0 = lines[i].strip()
        link0_lines.append(l0)
        if l0.lower().startswith("%chk="):
            chk_val = l0.split("=", 1)[1].strip()
            if "/" in chk_val or "\\" in chk_val or ".." in chk_val:
                errors.append(f"Unsafe %chk path separator/traversal detected: {chk_val!r}")
        elif l0.lower().startswith("%nproc"):
            val = l0.split("=", 1)[1].strip()
            if not val.isdigit() or int(val) <= 0:
                errors.append(f"Invalid processor directive: {l0}")
        i += 1

    while i < len(lines) and lines[i].strip().startswith("#"):
        route_lines.append(lines[i].strip())
        i += 1
    if not route_lines:
        errors.append("Missing route section line starting with '#'")

    while i < len(lines) and lines[i].strip():
        route_lines.append(lines[i].strip())
        i += 1

    if i >= len(lines) or lines[i].strip() != "":
        errors.append("Missing blank line terminating route section")
        return {"valid": False, "errors": errors, "warnings": warnings}
    i += 1

    title_lines: List[str] = []
    while i < len(lines) and lines[i].strip():
        title_lines.append(lines[i].strip())
        i += 1
    if not title_lines:
        errors.append("Missing title line")
    if i >= len(lines) or lines[i].strip() != "":
        errors.append("Missing blank line terminating title section")
        return {"valid": False, "errors": errors, "warnings": warnings}
    i += 1

    if i >= len(lines):
        errors.append("Missing charge and multiplicity line")
        return {"valid": False, "errors": errors, "warnings": warnings}
    cm_parts = lines[i].strip().split()
    charge = 0
    mult = 1
    if len(cm_parts) < 2:
        errors.append(f"Invalid charge/multiplicity line: {lines[i]!r}")
    else:
        try:
            charge, mult = int(cm_parts[0]), int(cm_parts[1])
            if mult < 1:
                errors.append(f"Multiplicity must be >= 1, got {mult}")
        except ValueError:
            errors.append(f"Charge and multiplicity must be integers: {lines[i]!r}")
    i += 1

    atoms: List[Tuple[str, float, float, float]] = []
    while i < len(lines) and lines[i].strip():
        parts = lines[i].strip().split()
        if len(parts) < 4:
            errors.append(f"Malformed coordinate row at line {i + 1}: {lines[i]!r}")
        else:
            try:
                atoms.append((parts[0], float(parts[1]), float(parts[2]), float(parts[3])))
            except ValueError:
                errors.append(f"Non-numeric coordinates at line {i + 1}: {lines[i]!r}")
        i += 1
    if not atoms:
        errors.append("No atomic coordinates found")
    else:
        warnings.extend(electron_parity_check(atoms, charge, mult))

    return {
        "valid": len(errors) == 0,
        "link0_count": len(link0_lines),
        "route": " ".join(route_lines),
        "title": " ".join(title_lines),
        "charge": charge,
        "multiplicity": mult,
        "atom_count": len(atoms),
        "errors": errors,
        "warnings": warnings,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description="Standalone Gaussian 16 .gjf generator and validator")
    sub = parser.add_subparsers(dest="cmd", required=True)

    p_xyz = sub.add_parser("xyz-to-gjf", help="Convert an XYZ coordinate file into a Gaussian .gjf file")
    p_xyz.add_argument("xyz_file", help="Path to input .xyz file")
    p_xyz.add_argument("-o", "--output", help="Optional path to write .gjf (prints to stdout if omitted)")
    p_xyz.add_argument("--method", default="B3LYP")
    p_xyz.add_argument("--basis", default="6-31G(d,p)")
    p_xyz.add_argument("--job-type", default="opt_freq", choices=list(JOB_PRESETS))
    p_xyz.add_argument("--charge", type=int, default=0)
    p_xyz.add_argument("--multiplicity", type=int, default=1)
    p_xyz.add_argument("--mem", default="8GB")
    p_xyz.add_argument("--nproc", type=int, default=4)
    p_xyz.add_argument("--chk", default="")
    p_xyz.add_argument("--solvent", default="")
    p_xyz.add_argument("--dispersion", default="")
    p_xyz.add_argument("--extra", default="")

    p_val = sub.add_parser("validate", help="Validate syntax and safety of an existing .gjf file")
    p_val.add_argument("gjf_file", help="Path to .gjf file")

    sub.add_parser("presets", help="List recommended task presets")

    args = parser.parse_args()
    if args.cmd == "presets":
        print(json.dumps({"job_presets": JOB_PRESETS}, indent=2))
        return 0
    if args.cmd == "xyz-to-gjf":
        title, atoms = parse_xyz(Path(args.xyz_file).read_text(encoding="utf-8", errors="replace"))
        warns = electron_parity_check(atoms, args.charge, args.multiplicity)
        gjf = build_gjf(
            atoms,
            method=args.method,
            basis=args.basis,
            job_type=args.job_type,
            charge=args.charge,
            multiplicity=args.multiplicity,
            mem=args.mem,
            nproc=args.nproc,
            chk=args.chk or f"{Path(args.xyz_file).stem}.chk",
            solvent=args.solvent,
            dispersion=args.dispersion,
            title=title,
            extra_keywords=args.extra,
        )
        if args.output:
            Path(args.output).write_text(gjf, encoding="utf-8", newline="\n")
        else:
            sys.stdout.write(gjf)
        for w in warns:
            print(f"[WARNING] {w}", file=sys.stderr)
        return 0 if not warns else 2
    if args.cmd == "validate":
        report = validate_gjf(Path(args.gjf_file).read_text(encoding="utf-8", errors="replace"))
        print(json.dumps(report, indent=2, ensure_ascii=False))
        return 0 if report["valid"] else 1
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
